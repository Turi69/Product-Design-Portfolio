# Renders public/Turi-Ogefere-Resume.pdf into page images for the in-site viewer.
# Run after replacing the PDF:  python tools/resume-pages.py
# Needs: pip install pymupdf pillow
import io
import json
import pathlib

import pymupdf
from PIL import Image

root = pathlib.Path(__file__).resolve().parent.parent
pdf = root / 'public' / 'Turi-Ogefere-Resume.pdf'
out = root / 'public' / 'assets' / 'resume'
out.mkdir(parents=True, exist_ok=True)

# 300 dpi: an A4 page is ~2480px wide, crisp up to the viewer's 300% zoom.
DPI = 300
pages = []
for i, page in enumerate(pymupdf.open(pdf), start=1):
    png = page.get_pixmap(dpi=DPI, alpha=False).tobytes('png')
    img = Image.open(io.BytesIO(png))
    name = f'page-{i}.webp'
    # Lossless: text on white compresses better this way than lossy, and stays sharp.
    img.save(out / name, 'WEBP', lossless=True, method=6)
    pages.append({'src': f'/assets/resume/{name}', 'width': img.width, 'height': img.height})

(root / 'src' / 'data' / 'resumePages.ts').write_text(
    '// Generated by tools/resume-pages.py: the résumé PDF as page images for the viewer.\n'
    'export const resumePages: { src: string; width: number; height: number }[] = '
    + json.dumps(pages, indent=2) + ';\n',
    encoding='utf-8',
)
print(f'{len(pages)} pages written to {out}')
